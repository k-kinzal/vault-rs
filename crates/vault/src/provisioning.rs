//! Authenticated provisioning output. Hypervisor console and state-disk hashes
//! alone never establish the origin of a newly generated database envelope.
use crate::{
    crypto::{self, Signed},
    keys::{KeyRole, RuntimeKeyConfig},
};
use anyhow::{ensure, Result};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::path::Path;

#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Receipt {
    pub operation: String,
    pub nonce: String,
    pub source_sha256: String,
    pub binary_sha256: String,
    pub output: String,
    /// Hash computed from the newly generated bytes in private guest memory,
    /// before writing to the untrusted state disk; never a post-write reread.
    pub output_sha256: String,
    pub observation: Option<crate::readiness::Observed>,
}
pub fn sign(
    operation: &str,
    nonce: &str,
    output: &Path,
    pin: String,
    observation: Option<crate::readiness::Observed>,
    key_path: &Path,
) -> Result<Signed<Receipt>> {
    ensure!(
        hex::decode(nonce)?.len() == 32 && hex::decode(&pin)?.len() == 32,
        "32-byte provisioning nonce and output digest required"
    );
    crate::runner::protected_path(key_path)?;
    let key: RuntimeKeyConfig =
        serde_json::from_slice(&crate::runner::read_bounded(key_path, 65536)?)?;
    key.require_confidential()?;
    let key = key.open(KeyRole::ServiceSigning)?;
    let payload = Receipt {
        operation: operation.into(),
        nonce: nonce.into(),
        source_sha256: crate::readiness::SOURCE_SHA256.into(),
        binary_sha256: hex::encode(Sha256::digest(crate::runner::read_bounded(
            &std::env::current_exe()?,
            128 * 1024 * 1024,
        )?)),
        output: output.to_string_lossy().into(),
        output_sha256: pin,
        observation,
    };
    let signature = key.sign_bytes(&crypto::transcript("snp-provisioning-receipt", &payload)?)?;
    Ok(Signed { payload, signature })
}
pub fn verify(
    receipt: &Signed<Receipt>,
    public: &str,
    operation: &str,
    nonce: &str,
    output: &Path,
) -> Result<()> {
    crypto::verify("snp-provisioning-receipt", receipt, public)?;
    ensure!(
        receipt.payload.operation == operation
            && receipt.payload.nonce == nonce
            && Path::new(&receipt.payload.output) == output,
        "provisioning receipt does not match the operator's fixed intent"
    );
    ensure!(
        hex::decode(nonce)?.len() == 32 && hex::decode(&receipt.payload.output_sha256)?.len() == 32,
        "invalid provisioning binding"
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use p256::elliptic_curve::Generate;
    #[test]
    fn bootstrap_receipt_authenticates_nonce_generation_and_fixed_intent() {
        let key = p256::ecdsa::SigningKey::generate();
        let public = crypto::public(&key);
        let output = Path::new("/state/vault.db");
        let nonce = "12".repeat(32);
        let payload = Receipt {
            operation: "initialize-storage".into(),
            nonce: nonce.clone(),
            source_sha256: "34".repeat(32),
            binary_sha256: "56".repeat(32),
            output: output.to_string_lossy().into(),
            output_sha256: "78".repeat(32),
            observation: None,
        };
        let signed = crypto::sign("snp-provisioning-receipt", &payload, &key).unwrap();
        verify(&signed, &public, "initialize-storage", &nonce, output).unwrap();
        assert!(verify(&signed, &public, "rotate-storage", &nonce, output).is_err());
        assert!(verify(
            &signed,
            &public,
            "initialize-storage",
            &"00".repeat(32),
            output
        )
        .is_err());
        assert!(verify(
            &signed,
            &public,
            "initialize-storage",
            &nonce,
            Path::new("/state/other.db")
        )
        .is_err());
        let mut forged = signed.clone();
        forged.payload.output_sha256 = "00".repeat(32);
        assert!(verify(&forged, &public, "initialize-storage", &nonce, output).is_err());
        let other_domain = crypto::sign("observe", &payload, &key).unwrap();
        assert!(verify(&other_domain, &public, "initialize-storage", &nonce, output).is_err());
    }
}
